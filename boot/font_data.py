def build_font():
    """Returns (font_bytes, index_table).

    font_bytes: glyphs in GLYPH_ORDER, 16 bytes each.
    index_table: 128 bytes, ASCII code -> glyph index, 0xFF = no glyph.
    """
    assert set(G.keys()) == set(GLYPH_ORDER), "glyph set mismatch"
    font = bytearray()
    for ch in GLYPH_ORDER:
        rows = G[ch]
        assert len(rows) == 16 and all(len(r) == 8 for r in rows), ch
        for r in rows:
            assert set(r) <= {".", "#"}, (ch, r)
            v = 0
            for c in r:
                v = (v << 1) | (c == "#")
            font.append(v)
    index = bytearray([0xFF] * 128)
    for i, ch in enumerate(GLYPH_ORDER):
        index[ord(ch)] = i
    return bytes(font), bytes(index)
